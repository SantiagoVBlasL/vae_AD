def filter_primary_metrics(df: pd.DataFrame, readout_feature_set: str) -> pd.DataFrame:
    out = df.copy()
    if "readout_feature_set" not in out.columns:
        out["readout_feature_set"] = "z_plus_age_sex"
    mask = (
        out["model_name"].astype(str).eq(PRIMARY_MODEL)
        & out["threshold_strategy"].astype(str).eq(PRIMARY_THRESHOLD)
        & out["readout_feature_set"].astype(str).eq(str(readout_feature_set))
    )
    return out.loc[mask].copy()


def collect_stage_b(row: pd.Series) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    readout_dir = Path(str(row["readout_dir"]))
    pooled_rows: List[pd.DataFrame] = []
    fold_rows: List[pd.DataFrame] = []
    threshold_rows: List[pd.DataFrame] = []
    subgroup_rows: List[pd.DataFrame] = []
    confusion_rows: List[pd.DataFrame] = []
    if (readout_dir / "classifier_sweep_pooled_metrics.csv").exists():
        pooled = filter_primary_metrics(pd.read_csv(readout_dir / "classifier_sweep_pooled_metrics.csv"), str(row["readout_feature_set"]))
        if not pooled.empty:
            pooled_rows.append(add_candidate_metadata(pooled, row))
    if (readout_dir / "classifier_sweep_foldwise_metrics.csv").exists():
        fold = filter_primary_metrics(pd.read_csv(readout_dir / "classifier_sweep_foldwise_metrics.csv"), str(row["readout_feature_set"]))
        if not fold.empty:
            fold_rows.append(add_candidate_metadata(fold, row))
    if (readout_dir / "classifier_sweep_thresholds_by_fold.csv").exists():
        th = pd.read_csv(readout_dir / "classifier_sweep_thresholds_by_fold.csv")
        if "readout_feature_set" not in th.columns:
            th["readout_feature_set"] = "z_plus_age_sex"
        th = th[
            th["model_name"].astype(str).eq(PRIMARY_MODEL)
            & th["threshold_strategy"].astype(str).eq(PRIMARY_THRESHOLD)
            & th["readout_feature_set"].astype(str).eq(str(row["readout_feature_set"]))
        ].copy()
        if not th.empty:
            threshold_rows.append(add_candidate_metadata(th, row))
    if (readout_dir / "classifier_sweep_subgroup_metrics_by_manufacturer.csv").exists():
        sg = pd.read_csv(readout_dir / "classifier_sweep_subgroup_metrics_by_manufacturer.csv")
        if "readout_feature_set" not in sg.columns:
            sg["readout_feature_set"] = "z_plus_age_sex"
        sg = sg[
            sg["model_name"].astype(str).eq(PRIMARY_MODEL)
            & sg["threshold_strategy"].astype(str).eq(PRIMARY_THRESHOLD)
            & sg["readout_feature_set"].astype(str).eq(str(row["readout_feature_set"]))
        ].copy()
        if not sg.empty:
            subgroup_rows.append(add_candidate_metadata(sg, row))
    if (readout_dir / "classifier_sweep_confusion_by_fold.csv").exists():
        cf = pd.read_csv(readout_dir / "classifier_sweep_confusion_by_fold.csv")
        if "readout_feature_set" not in cf.columns:
            cf["readout_feature_set"] = "z_plus_age_sex"
        cf = cf[
            cf["model_name"].astype(str).eq(PRIMARY_MODEL)
            & cf["threshold_strategy"].astype(str).eq(PRIMARY_THRESHOLD)
            & cf["readout_feature_set"].astype(str).eq(str(row["readout_feature_set"]))
        ].copy()
        if not cf.empty:
            confusion_rows.append(add_candidate_metadata(cf, row))
    empty = pd.DataFrame()
    return (
        pd.concat(pooled_rows, ignore_index=True, sort=False) if pooled_rows else empty,
        pd.concat(fold_rows, ignore_index=True, sort=False) if fold_rows else empty,
        pd.concat(threshold_rows, ignore_index=True, sort=False) if threshold_rows else empty,
        pd.concat(subgroup_rows, ignore_index=True, sort=False) if subgroup_rows else empty,
        pd.concat(confusion_rows, ignore_index=True, sort=False) if confusion_rows else empty,
    )


