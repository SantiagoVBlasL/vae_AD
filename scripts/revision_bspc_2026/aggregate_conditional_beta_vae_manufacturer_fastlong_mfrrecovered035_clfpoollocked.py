def _split_subjects(path: Path) -> Tuple[set, pd.DataFrame]:
    if not path.exists():
        return set(), pd.DataFrame()
    df = pd.read_csv(path)
    subjects = set(df.get("SubjectID", pd.Series(dtype=str)).astype(str).tolist())
    return subjects, df


def collect_supervised_exclusion_audit(manifest: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for _, row in manifest.iterrows():
        run_dir = Path(str(row["run_dir"]))
        for fold in range(1, 4):
            for split, filename in [("train_dev", "train_dev_subjects_fold.csv"), ("test", "test_subjects_fold.csv")]:
                path = run_dir / f"fold_{fold}" / filename
                subjects, df = _split_subjects(path)
                counts = df.get("ResearchGroup_Mapped", pd.Series(dtype=str)).astype(str).value_counts().to_dict() if not df.empty else {}
                contains_035 = PATCHED_SUBJECT in subjects
                contains_128 = UNRESOLVED_SUBJECT in subjects
                status = "missing" if df.empty else ("violation" if contains_035 or contains_128 else "ok")
                rows.append({
                    "candidate_id": row["candidate_id"],
                    "fold": fold,
                    "split": split,
                    "path": str(path),
                    "status": status,
                    "n": int(len(df)) if not df.empty else 0,
                    "CN": int(counts.get("CN", 0)),
                    "AD": int(counts.get("AD", 0)),
                    "contains_035_S_6927": bool(contains_035),
                    "contains_128_S_2002": bool(contains_128),
                })
    return pd.DataFrame(rows)


def collect_classifier_pool_identity_vs_cleanmfr(manifest: pd.DataFrame, cleanmfr_root: Path) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for _, row in manifest.iterrows():
        candidate = str(row["candidate_id"])
        run_dir = Path(str(row["run_dir"]))
        clean_run_dir = cleanmfr_root / "runs" / candidate
        for fold in range(1, 4):
            for split, filename in [("train_dev", "train_dev_subjects_fold.csv"), ("test", "test_subjects_fold.csv")]:
                this_subjects, this_df = _split_subjects(run_dir / f"fold_{fold}" / filename)
                clean_subjects, clean_df = _split_subjects(clean_run_dir / f"fold_{fold}" / filename)
                only_this = sorted(this_subjects - clean_subjects)
                only_clean = sorted(clean_subjects - this_subjects)
                status = "missing" if this_df.empty or clean_df.empty else ("identical" if not only_this and not only_clean else "different")
                rows.append({
                    "candidate_id": candidate,
                    "fold": fold,
                    "split": split,
                    "status": status,
                    "n_this": int(len(this_subjects)),
                    "n_cleanmfr": int(len(clean_subjects)),
                    "symmetric_difference_n": int(len(only_this) + len(only_clean)),
                    "only_this": "|".join(only_this[:20]),
                    "only_cleanmfr": "|".join(only_clean[:20]),
                })
    return pd.DataFrame(rows)


