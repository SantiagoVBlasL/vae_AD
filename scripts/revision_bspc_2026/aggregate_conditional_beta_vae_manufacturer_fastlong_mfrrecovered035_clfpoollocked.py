def get_baseline_row(primary: pd.DataFrame, channels: str, readout: str) -> Optional[pd.Series]:
    baseline_id = f"{'ch1_0_2' if channels == '[1, 0, 2]' else 'ch1'}_baseline_unconditioned"
    rows = primary[primary["candidate_id"].astype(str).eq(baseline_id)]
    if rows.empty:
        return None
    return rows.iloc[0]


def mean_mi_for(latent: pd.DataFrame, candidate_id: str, variable: str) -> float:
    if latent.empty:
        return np.nan
    sub = latent[latent["candidate_id"].astype(str).eq(candidate_id) & latent["latent_split"].astype(str).eq("test") & latent["variable"].astype(str).eq(variable)]
    if sub.empty or "mi_sum_nats" not in sub.columns:
        return np.nan
    return float(pd.to_numeric(sub["mi_sum_nats"], errors="coerce").mean())


def mean_leakage_for(leakage: pd.DataFrame, candidate_id: str) -> float:
    if leakage.empty or "acc_site_latent" not in leakage.columns:
        return np.nan
    sub = leakage[leakage["candidate_id"].astype(str).eq(candidate_id) & leakage["leakage_split"].astype(str).eq("test")]
    if sub.empty:
        return np.nan
    return float(pd.to_numeric(sub["acc_site_latent"], errors="coerce").mean())


def mean_predictability_for(predictability: pd.DataFrame, candidate_id: str, target: str) -> float:
    if predictability.empty or "balanced_accuracy" not in predictability.columns:
        return np.nan
    sub = predictability[predictability["candidate_id"].astype(str).eq(candidate_id) & predictability["target"].astype(str).eq(target)]
    if sub.empty:
        return np.nan
    return float(pd.to_numeric(sub["balanced_accuracy"], errors="coerce").mean())


def worst_manufacturer_metric(subgroups: pd.DataFrame, candidate_id: str, metric: str) -> float:
    if subgroups.empty or metric not in subgroups.columns:
        return np.nan
    sub = subgroups[subgroups["candidate_id"].astype(str).eq(candidate_id)].copy()
    if sub.empty:
        return np.nan
    return float(pd.to_numeric(sub[metric], errors="coerce").min())


def recommendation(
    primary: pd.DataFrame,
    latent: pd.DataFrame,
    leakage: pd.DataFrame,
    predictability: pd.DataFrame,
    subgroups: pd.DataFrame,
    pooled_metric_audit: pd.DataFrame,
) -> str:
    lines = [
        "# Conditional Manufacturer beta-VAE FAST-long 3x3 — recovered-035 VAE pool, classifier pool locked — Recommendation",
        "",
        "## Baseline validity",
        "",
        "Both focused FAST-long candidates in this experiment used `--vae_required_metadata_cols Manufacturer`,",
        "the branch-local patched metadata (035_S_6927 Manufacturer=SIEMENS restored),",
        "and `--classifier_exclude_subject_ids 035_S_6927`.",
        "",
        "**Primary comparators: clfpoollocked matched baselines only.**",
        "  - `ch1_0_2_baseline_unconditioned` → baseline for `ch1_0_2_decoder_only_manufacturer`",
        "",
        "The FAST-long target is `[1,0,2]`, not `[1]`, because the training-maturity audit identified",
        "`ch1_0_2_decoder_only_manufacturer` as the strongest valid diagnostic candidate: positive",
        "AUC and PR-AUC deltas, positive Manufacturer-leakage reduction, and 2/3 right-censored or",
        "near-horizon folds.",
        "",
        "cleanmfr is used only to audit classifier split identity, not as a primary performance comparator.",
        "",
        "## Decision rule",
        "",
        "Recommend FULL 5x5 only if Manufacturer conditioning improves or matches AUC/PR-AUC versus",
        "the matched clfpoollocked unconditioned baseline, has Sens >= 0.70, does not worsen BA/F1,",
        "reduces manufacturer/site leakage or Manufacturer predictability from z.",
        "",
    ]
    if primary.empty:
        lines.append("No completed Stage B primary metrics found. No FULL confirmation justified yet.")
        return "\n".join(lines) + "\n"

    if not pooled_metric_audit.empty and not pooled_metric_audit["pool_locked_ok"].all():
        lines.append("## Classifier Pool Lock Failure")
        lines.append("")
        lines.append("At least one candidate did not preserve n=396, CN=300, AD=96. Treat results as diagnostic only.")
        lines.append("")

    numeric_cols = ["auc", "pr_auc", "balanced_accuracy", "sensitivity", "specificity", "f1"]
    for col in numeric_cols:
        if col in primary.columns:
            primary[col] = pd.to_numeric(primary[col], errors="coerce")

    candidates = primary[primary["vae_conditioning_mode"].astype(str).eq("decoder_only")].copy()
    decisions = []
    for _, cand in candidates.iterrows():
        readout = str(cand["readout_feature_set"])
        baseline = get_baseline_row(primary, str(cand["channels"]), readout)
        if baseline is None:
            decisions.append((cand["candidate_id"], "no_mfrrecovered035_baseline_found", False))
            continue

        mfr_mi = mean_mi_for(latent, str(cand["candidate_id"]), "Manufacturer")
        base_mfr_mi = mean_mi_for(latent, str(baseline["candidate_id"]), "Manufacturer")
        mfr_pred = mean_predictability_for(predictability, str(cand["candidate_id"]), "Manufacturer")
        base_mfr_pred = mean_predictability_for(predictability, str(baseline["candidate_id"]), "Manufacturer")
        leak = mean_leakage_for(leakage, str(cand["candidate_id"]))
        base_leak = mean_leakage_for(leakage, str(baseline["candidate_id"]))
        worst_ba = worst_manufacturer_metric(subgroups, str(cand["candidate_id"]), "balanced_accuracy")
        base_worst_ba = worst_manufacturer_metric(subgroups, str(baseline["candidate_id"]), "balanced_accuracy")

        mi_ok = not (np.isfinite(mfr_mi) and np.isfinite(base_mfr_mi)) or mfr_mi <= base_mfr_mi
        pred_ok = not (np.isfinite(mfr_pred) and np.isfinite(base_mfr_pred)) or mfr_pred <= base_mfr_pred
        leak_ok = not (np.isfinite(leak) and np.isfinite(base_leak)) or leak <= base_leak
        nuisance_ok = mi_ok or pred_ok or leak_ok
        subgroup_ok = not (np.isfinite(worst_ba) and np.isfinite(base_worst_ba)) or worst_ba >= base_worst_ba - 0.005

        ok = (
            float(cand.get("auc", np.nan)) >= float(baseline.get("auc", np.inf))
            and float(cand.get("pr_auc", np.nan)) >= float(baseline.get("pr_auc", np.inf))
            and float(cand.get("sensitivity", np.nan)) >= 0.70
            and float(cand.get("balanced_accuracy", np.nan)) >= float(baseline.get("balanced_accuracy", np.inf))
            and float(cand.get("f1", np.nan)) >= float(baseline.get("f1", np.inf))
            and nuisance_ok
            and subgroup_ok
        )

        # Add cleanmfr reference as secondary context
        cleanmfr_ref = CLEANMFR_REFERENCE.get(str(cand["candidate_id"]), {})
        cleanmfr_base_ref = CLEANMFR_REFERENCE.get(str(baseline["candidate_id"]), {})
        cleanmfr_note = ""
        if cleanmfr_ref and cleanmfr_base_ref:
            cleanmfr_note = (
                f" [cleanmfr secondary ref: cand AUC={cleanmfr_ref.get('auc','?'):.4f}/"
                f"PR-AUC={cleanmfr_ref.get('pr_auc','?'):.4f} vs "
                f"cleanmfr_base AUC={cleanmfr_base_ref.get('auc','?'):.4f}/"
                f"PR-AUC={cleanmfr_base_ref.get('pr_auc','?'):.4f}]"
            )

        reason = (
            f"vs clfpoollocked baseline {baseline['candidate_id']}: "
            f"AUC {cand.get('auc', np.nan):.4f} vs {baseline.get('auc', np.nan):.4f}, "
            f"PR-AUC {cand.get('pr_auc', np.nan):.4f} vs {baseline.get('pr_auc', np.nan):.4f}, "
            f"ManufacturerMI {mfr_mi:.4f} vs {base_mfr_mi:.4f}, "
            f"ManufacturerPredBA {mfr_pred:.4f} vs {base_mfr_pred:.4f}, "
            f"latent leakage {leak:.4f} vs {base_leak:.4f}"
            + cleanmfr_note
        )
        decisions.append((cand["candidate_id"], reason, ok))

    promoted = [d for d in decisions if d[2]]
    if promoted:
        lines.append("Recommended for one controlled FULL 5x5 confirmation:")
        for candidate_id, reason, _ in promoted:
            lines.append(f"- `{candidate_id}`: {reason}")
    else:
        lines.append("No conditional candidate satisfies the full promotion rule based on currently completed outputs.")
    lines.append("")
    lines.append("Candidate checks (vs matched clfpoollocked baselines):")
    for candidate_id, reason, ok in decisions:
        lines.append(f"- `{candidate_id}`: {'PASS' if ok else 'NO_PROMOTE'}; {reason}")
    lines.append("")
    lines.append("## Secondary reference: cleanmfr results")
    lines.append("")
    lines.append("| candidate_id | cleanmfr_auc | cleanmfr_pr_auc |")
    lines.append("| --- | --- | --- |")
    for cid, vals in CLEANMFR_REFERENCE.items():
        lines.append(f"| {cid} | {vals['auc']:.4f} | {vals['pr_auc']:.4f} |")
    lines.append("")
    lines.append("Note: cleanmfr is retained here only as classifier-pool identity reference.")
    return "\n".join(lines) + "\n"


