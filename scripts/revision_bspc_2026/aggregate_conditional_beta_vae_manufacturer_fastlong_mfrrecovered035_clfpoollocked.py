def collect_rate_distortion(row: pd.Series) -> pd.DataFrame:
    run_dir = Path(str(row["run_dir"]))
    rows: List[Dict[str, Any]] = []
    for fold in range(1, 4):
        path = run_dir / f"fold_{fold}" / f"fold_{fold}_rate_distortion.csv"
        if not path.exists():
            continue
        df = pd.read_csv(path)
        if df.empty or "L_val_betaMax" not in df.columns:
            continue
        idx = df["L_val_betaMax"].astype(float).idxmin()
        rec = df.loc[idx].to_dict()
        d_val = float(rec.get("D_val", np.nan))
        r_val = float(rec.get("R_val_nats", np.nan))
        beta = 2.5
        rec.update({
            "candidate_id": row["candidate_id"],
            "condition_id": row["condition_id"],
            "channels": row["channels"],
            "readout_feature_set": row["readout_feature_set"],
            "fold": fold,
            "best_epoch_by_val_beta_max": int(rec.get("epoch", idx + 1)),
            "val_kld_over_recon": r_val / d_val if np.isfinite(r_val) and np.isfinite(d_val) and d_val else np.nan,
            "val_beta_kld_over_recon": beta * r_val / d_val if np.isfinite(r_val) and np.isfinite(d_val) and d_val else np.nan,
            "final_epoch_in_rd_file": int(df["epoch"].max()) if "epoch" in df.columns else np.nan,
        })
        rows.append(rec)
    return pd.DataFrame(rows)


