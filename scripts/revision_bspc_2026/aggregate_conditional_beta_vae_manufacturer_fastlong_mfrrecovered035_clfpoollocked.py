def read_matrix(preflight_root: Path) -> pd.DataFrame:
    path = preflight_root / "experiment_matrix.csv"
    if not path.exists():
        raise FileNotFoundError(f"Missing preflight matrix: {path}")
    df = pd.read_csv(path)
    missing_candidates = [c for c in EXPECTED_CANDIDATES if c not in set(df["candidate_id"].astype(str))]
    if missing_candidates:
        raise ValueError(f"Preflight matrix missing expected FAST-long candidates: {missing_candidates}")
    df = df[df["candidate_id"].astype(str).isin(EXPECTED_CANDIDATES)].copy()
    order = {candidate_id: idx for idx, candidate_id in enumerate(EXPECTED_CANDIDATES)}
    df["_order"] = df["candidate_id"].map(order)
    df = df.sort_values("_order").drop(columns=["_order"]).reset_index(drop=True)
    if "condition_id" not in df.columns:
        df["condition_id"] = df["candidate_id"].astype(str).str.replace("^ch1_0_2_", "", regex=True).str.replace("^ch1_", "", regex=True)
    if "corr_lambda" not in df.columns:
        df["corr_lambda"] = 0.0
    return df


def parse_channels(value: Any) -> List[int]:
    parsed = ast.literal_eval(str(value))
    if not isinstance(parsed, list):
        raise ValueError(f"Invalid channels field: {value!r}")
    return [int(x) for x in parsed]


def load_run_manifest(output_root: Path, preflight_root: Path) -> pd.DataFrame:
    manifest_path = output_root / "run_manifest.csv"
    matrix = read_matrix(preflight_root)
    rows = []
    for _, row in matrix.iterrows():
        run_dir = output_root / "runs" / str(row["candidate_id"])
        rows.append({
            **row.to_dict(),
            "run_dir": str(run_dir),
            "readout_dir": str(run_dir / f"classifier_only_readout_{row['readout_feature_set']}"),
        })
    canonical = pd.DataFrame(rows)
    if not manifest_path.exists():
        return canonical
    manifest = pd.read_csv(manifest_path)
    if manifest.get("candidate_id", pd.Series(dtype=str)).tolist() == EXPECTED_CANDIDATES:
        return manifest
    if "candidate_id" in manifest.columns:
        manifest_by_id = manifest.set_index("candidate_id", drop=False)
        for idx, row in canonical.iterrows():
            candidate = row["candidate_id"]
            if candidate in manifest_by_id.index:
                for col in ["run_dir", "readout_dir", "big_run_dir"]:
                    if col in manifest_by_id.columns and pd.notna(manifest_by_id.loc[candidate, col]):
                        canonical.at[idx, col] = manifest_by_id.loc[candidate, col]
    return canonical


def add_candidate_metadata(df: pd.DataFrame, row: pd.Series) -> pd.DataFrame:
    out = df.copy()
    for key in ["candidate_id", "condition_id", "channels", "channel_names", "vae_conditioning_mode", "vae_conditioning_vars", "corr_lambda", "readout_feature_set"]:
        if key in row:
            out[key] = row[key]
    return out


