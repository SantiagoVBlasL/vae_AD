def sex_to_binary(values: pd.Series) -> Tuple[np.ndarray, bool]:
    mapped = values.astype(str).str.upper().map({"F": 1, "FEMALE": 1, "M": 0, "MALE": 0})
    ok = not mapped.isna().any() and mapped.nunique(dropna=True) == 2
    return mapped.to_numpy(dtype=float), bool(ok)


